# 3.  Canonical Implication Base (Duquenne-Guigues base)
#     (Guigues & Duquenne 1986; Ganter & Wille 1999 §2.4)
# ═══════════════════════════════════════════════════════════════════════════════

def _lin_closure(
    attr_set: FrozenSet[str],
    implications: List[Implication],
) -> FrozenSet[str]:
    """
    LinClosure: compute the closure of attr_set under a set of implications
    in linear time (Beeri & Bernstein 1979; Poelmans et al. 2013 §5.1.1).

    Used by NextClosure to check whether a set is pseudo-closed.
    """
    result = set(attr_set)
    changed = True
    while changed:
        changed = False
        for impl in implications:
            if impl.premise <= result and not impl.conclusion <= result:
                result |= impl.conclusion
                changed = True
    return frozenset(result)


def compute_implication_base(
    context: FormalContext,
    max_implications: int = 500,
) -> List[Implication]:
    """
    Compute the canonical (Duquenne-Guigues) implication base of K.
    (Guigues & Duquenne 1986; Ganter 1984 NextClosure; Ganter & Wille 1999 §2.4)

    A set P ⊆ M is pseudo-closed if:
      (i)  P is not closed: P ≠ P''
      (ii) For every pseudo-closed Q ⊊ P: Q'' ⊆ P

    The canonical base is { P → P'' \\ P | P is pseudo-closed }.
    It is the unique smallest implication base (Guigues & Duquenne 1986).

    Implementation: Ganter's NextClosure where the closure operator is
    LinClosure under the implications collected SO FAR (not the context
    closure). At each set A that is closed w.r.t. the current implications we
    compare A with its context closure A''; if they differ, A is pseudo-closed
    and we emit A → A''\\A. (The earlier version advanced via the *context*
    closure, so it only ever visited closed sets and found no implications.)
    """
    attrs = context.attributes
    n = len(attrs)

    implications: List[Implication] = []

    def clo_L(idx_set: set) -> set:
        """LinClosure of an index set under the current implication list."""
        names = _lin_closure(frozenset(attrs[i] for i in idx_set), implications)
        return {i for i, a in enumerate(attrs) if a in names}

    def next_closure(A: set) -> Optional[set]:
        """Ganter NextClosure successor of A under closure operator clo_L."""
        A = set(A)
        for i in range(n - 1, -1, -1):
            if i in A:
                A.discard(i)
            else:
                B = clo_L(A | {i})
                # B is the successor iff B and A agree on every j < i
                if not any(j < i for j in (B - A)):
                    return B
        return None

    A: Optional[set] = clo_L(set())          # closure of ∅ under (empty) L
    iterations = 0
    max_iter = 200000

    while A is not None and iterations < max_iter:
        iterations += 1
        names_A = frozenset(attrs[i] for i in A)
        ctx_closed = context.closure(names_A)        # A''
        if names_A != ctx_closed:
            conclusion = ctx_closed - names_A
            if conclusion:
                implications.append(
                    Implication(premise=names_A, conclusion=conclusion))
                if len(implications) >= max_implications:
                    break
        if len(A) == n:                              # reached full set M
            break
        A = next_closure(A)

    return implications


