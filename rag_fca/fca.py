# 4.  Hasse diagram construction
#     (Ganter & Wille 1999 §1.3 — line diagram of concept lattice)
# ═══════════════════════════════════════════════════════════════════════════════

def build_hasse_diagram(
    concepts: List[FormalConcept],
) -> List[Tuple[int, int]]:
    """
    Construct the Hasse diagram edges of the concept lattice
    (direct cover relations only, no transitive edges).

    (A1,B1) covers (A2,B2)  iff  A2 ⊂ A1 and ∄ C s.t. A2 ⊂ C ⊂ A1.
    Equivalently in terms of intents: B1 ⊂ B2 with no intermediate.

    Returns list of (child_idx, parent_idx) pairs.
    """
    n = len(concepts)
    # For each pair, check the subset relation on extents
    edges: List[Tuple[int, int]] = []

    for i in range(n):
        for j in range(n):
            if i == j:
                continue
            # i is candidate child, j is candidate parent
            if not concepts[i].extent < concepts[j].extent:
                continue
            # Check no intermediate concept
            is_direct = True
            for k in range(n):
                if k == i or k == j:
                    continue
                if concepts[i].extent < concepts[k].extent < concepts[j].extent:
                    is_direct = False
                    break
            if is_direct:
                edges.append((i, j))

    return edges


