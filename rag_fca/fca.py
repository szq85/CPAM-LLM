# 2.  NextClosure ALGORITHM — canonical concept enumeration
#     (Ganter 1984; Guigues & Duquenne 1986; Ganter & Wille 1999 §2.4)
# ═══════════════════════════════════════════════════════════════════════════════

def _lectic_next(
    current: List[bool],
    context: FormalContext,
    attr_order: List[str],
) -> Optional[List[bool]]:
    """
    Compute the lectic successor of 'current' attribute set in NextClosure.

    The lectic order on 2^M is: A <_i B  iff  i ∈ B\\A  and  A∩{0..i-1} = B∩{0..i-1}
    NextClosure advances to the smallest lectic successor that is closed.

    Algorithm (Ganter 1984):
      For i from |M|-1 down to 0:
        if i ∉ current:
          B = closure(current ∪ {i}) ∩ {0..i}
          if B is the i-lectically next (i.e., B and current agree on {0..i-1}
          and i ∈ B):
            return (current ∩ {0..i-1}) ∪ B
      return None  (current is the last closed set = M)
    """
    n = len(attr_order)
    for i in range(n - 1, -1, -1):
        if not current[i]:
            # Build candidate: (current ∩ {0..i-1}) ∪ {i}
            candidate_set = frozenset(
                attr_order[j] for j in range(i) if current[j]
            ) | {attr_order[i]}
            # Compute closure
            closed_set = context.closure(candidate_set)
            # Convert to bool array restricted to {0..i}
            closed_bits = [attr_order[j] in closed_set for j in range(n)]
            # Check lectic condition: agree on {0..i-1}, i ∈ closed
            agree = all(closed_bits[j] == current[j] for j in range(i))
            if agree and closed_bits[i]:
                return closed_bits
    return None


def enumerate_all_concepts(
    context: FormalContext,
    max_concepts: int = 2000,
) -> List[FormalConcept]:
    """
    Enumerate ALL formal concepts of K using NextClosure
    (Ganter 1984; Ganter & Wille 1999 §2.4).

    Starts from the smallest closed set (∅'' = M if no object has all attrs,
    or the closure of ∅), iterates in lectic order until exhausted.

    Returns list of FormalConcept ordered by lectic order of intent.

    Complexity: O(|G|·|M|·|L(K)|) where |L(K)| ≤ 2^min(|G|,|M|).
    For large contexts we cap at max_concepts to avoid exponential blowup
    (Poelmans et al. 2013 §5.5 — scalability).
    """
    attr_order = context.attributes   # fixed lectic order
    n = len(attr_order)

    concepts: List[FormalConcept] = []

    # Start: closure of ∅  (= intent of the TOP concept, since ∅' = G → G' = TOP intent)
    start_set = context.closure(frozenset())
    current = [a in start_set for a in attr_order]

    seen_intents: set = set()

    while True:
        intent = frozenset(a for a, v in zip(attr_order, current) if v)
        if intent not in seen_intents:
            seen_intents.add(intent)
            extent = context.attribute_prime(intent)
            concepts.append(FormalConcept(extent=extent, intent=intent))

        if len(concepts) >= max_concepts:
            break

        nxt = _lectic_next(current, context, attr_order)
        if nxt is None:
            break
        current = nxt

    return concepts


