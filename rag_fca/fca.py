def _cue_in(cue: str, low: str) -> bool:
    """Cue match: multi-word phrases use substring match; single short words use
    word-boundary match, so 'van' does not hit 'advanced', 'arc' does not hit
    'search', and 'tsp'/'vrp' do not hit unrelated substrings."""
    if " " in cue or "-" in cue:
        return cue in low
    return _re_cue.search(r"\b" + _re_cue.escape(cue) + r"\b", low) is not None


def _strong_cue_hits(low: str) -> dict:
    return {dom: sum(1 for c in cues if _cue_in(c, low))
            for dom, cues in _DOMAIN_STRONG_CUES.items()}


def detect_scenario_strong(q: str) -> str:
    """Decide the scenario using domain-specific strong keywords only; return ''
    when uncertain.

    The strong keywords of the 5 domains do not overlap. Rules:
      - exactly one domain matches -> return it;
      - several match (rare) -> return only if one clearly leads (by >= 2),
        otherwise return '';
      - none match -> return '' (defer to FCA concept-overlap / weighted cues).

    Purpose: hard-localize the domain before any upper-level type is known, so
    VRP / charging / battery are not mislabeled by shared generic words. Note:
    'vehicle' is in no strong-keyword table, so charging/battery problems that
    mention 'electric vehicle' are not misclassified as VRP.
    """
    low = (q or "").lower()
    hits = _strong_cue_hits(low)
    present = {d: h for d, h in hits.items() if h > 0}
    if not present:
        return ""
    if len(present) == 1:
        return next(iter(present))
    ranked = sorted(present.items(), key=lambda kv: -kv[1])
    if ranked[0][1] - ranked[1][1] >= 2:
        return ranked[0][0]
    return ""  # strong keyworddistinct →


def _detect_scenario(q: str) -> str:
    """Detect the problem scenario from NL text (lowercased input).

    First try domain-specific strong keywords (detect_scenario_strong); return on
    a hit. Otherwise fall back to weighted cue counting, where cross-domain generic
    words (vehicle/machine/job/charging...) get low weight and specific words get
    high weight, so generic words do not dominate.
    """
    low = (q or "").lower()
    strong = detect_scenario_strong(low)
    if strong:
        return strong

    # but strong keywordalready
    domain_cues = {
        "Aircraft Skin Processing": [("aircraft", 3), ("skin", 3), ("job shop", 3),
            ("makespan", 3), ("processing time", 2), ("operation", 1),
            ("machine", 1), ("job", 1), ("robot", 1)],
        "Battery Pack Design":      [("battery", 3), ("module", 2), ("voltage", 2),
            ("energy storage", 2), ("photovoltaic", 2), ("series column", 3),
            ("energy loss", 2), ("pack", 1), ("cell", 1)],
        "Charging Station Location":[("charging station", 3), ("demand area", 3),
            ("facility location", 3), ("charging", 2), ("service coverage", 2),
            ("facility", 1), ("site", 1)],
        "DNA Sequence Design":      [("dna", 3), ("nucleotide", 3), ("gc content", 3),
            ("watson", 2), ("base pair", 2), ("sequence", 1)],
        "VRP":                      [("depot", 3), ("routing", 3), ("subtour", 3),
            ("truck", 3), ("fleet", 2), ("route", 2), ("customer", 2),
            ("delivery", 2), ("logistics", 1), ("deliver", 1),
            ("visited exactly once", 2), ("vehicle", 1)],
    }
    scen, best = None, 0
    for s, cues in domain_cues.items():
        hits = sum(w for c, w in cues if c in low)
        if hits > best:
            best, scen = hits, s
    return scen or ""


def extract_query_attributes(
    query_text: str, all_attributes: List[str], force_scenario: str = None,
    include_base: bool = True,
) -> FrozenSet[str]:
    """
    Extract the crisp attribute set Q' from a query (paper Eq. 15 semantic
    disambiguation). Three complementary signals:
      (a) detect the scenario from anchor/domain keywords → add its anchor;
      (b) apply the per-scenario NL constraint signatures (constraints.CATALOG)
          so phrasings like "tight start time window" map to the right named
          constraint type — not just literal attribute-name substrings;
      (c) fall back to attribute-name substring matching for any extras.

    force_scenario:
        Pass this when the upper level has reliably decided the type (e.g. the NL
        keyword detector confirmed 'VRP'). Then only that scenario's catalog is
        used (anchor + base + objective + matched optional signatures), and the
        cross-domain literal fallback (c) is SKIPPED, preventing other domains'
        (e.g. job-shop) attributes from leaking in. Otherwise, once a VRP text
        contains words like 'job'/'machine', FJSP attributes would be pulled in by
        (c) and drag retrieval back to job-shop concepts.

    include_base:
        When True (default) the scenario's *base* constraints are injected — this
        is what retrieval/augmentation needs. When False, the base set is NOT
        injected, so the result is the *explicitly stated* attribute set (anchor +
        objective + matched optional signatures). The rough-set implicit-constraint
        discovery (paper Alg., Eq. 19-22) must run on this explicit seed: if the
        base were already injected, the lower approximation (certain constraints)
        would be empty by construction, since those base constraints are exactly
        what the lower approximation is meant to *discover*.
    """
    import re as _re
    q = query_text.lower()
    found: set = set()

    try:
        from rag_fca import constraints as _con
    except Exception:
        _con = None

    scoped = bool(force_scenario)
    if _con is not None:
        # (a) scenario detection via robust domain disambiguation
        scen = force_scenario or _detect_scenario(q)

        scenarios = [scen] if scen else list(_con.CATALOG.keys())
        for s in scenarios:
            spec = _con.CATALOG.get(s)
            if not spec:
                continue
            found.add(spec["anchor"])
            # base constraints are implied by the scenario
            if include_base:
                found.update(spec["base"])
            found.add(spec["objective"])
            # (b) optional constraints via NL signatures
            for opt in spec["optional"]:
                if _re.search(opt["regex"], query_text):
                    if opt.get("relax"):
                        found.discard(opt["relax"])
                    found.add(opt["name"])

    # (c) literal attribute-name fallback only
    # VRP 'job'/'machine' FJSP
    if not scoped:
        for a in all_attributes:
            if a.lower() in q or a.replace("_", " ").lower() in q:
                found.add(a)

    return frozenset(a for a in found if a in all_attributes)


def extract_query_memberships(
    query_text: str, all_attributes: List[str]
) -> Dict[str, float]:
    """
    Extract fuzzy attribute memberships from query text.
    µ_Q(m) ∈ [0,1] via log term frequency.
    """
    q = query_text.lower()
    memberships: Dict[str, float] = {}
    for a in all_attributes:
        variants = [a.lower(), a.replace("_", " ").lower(), a.replace("_", "").lower()]
        count = sum(q.count(v) for v in variants)
        if count > 0:
            memberships[a] = min(1.0, math.log1p(count) / math.log1p(5))
    return memberships


