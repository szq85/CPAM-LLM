@dataclass
class FormalContext:
    """
    Formal context K = (G, M, I)  [Ganter & Wille 1999, Def. 1]

    objects    : G — list of object identifiers (KB record IDs)
    attributes : M — list of attribute names (CP-domain keywords)
    relation   : |G|×|M| boolean incidence matrix  I ⊆ G × M
    object_data: mapping id → full record dict for downstream use
    """
    objects:     List[str]
    attributes:  List[str]
    relation:    np.ndarray       # bool matrix [|G| × |M|]
    object_data: Dict             # id -> full record dict

    # ── Galois connection operators ──────────────────────────────────────────

    def object_prime(self, obj_set: FrozenSet[str]) -> FrozenSet[str]:
        """
        A' = { m ∈ M | ∀g ∈ A, (g,m) ∈ I }  (Eq. 12)

        The set of attributes shared by ALL objects in obj_set.
        Empty input → all attributes (top element of the lattice).
        """
        if not obj_set:
            return frozenset(self.attributes)
        idx = [self.objects.index(g) for g in obj_set if g in self.objects]
        if not idx:
            return frozenset()
        mask = np.all(self.relation[idx, :], axis=0)
        return frozenset(a for a, v in zip(self.attributes, mask) if v)

    def attribute_prime(self, attr_set: FrozenSet[str]) -> FrozenSet[str]:
        """
        B' = { g ∈ G | ∀m ∈ B, (g,m) ∈ I }  (Eq. 13)

        The set of objects that have ALL attributes in attr_set.
        Empty input → all objects (top element by extent).
        """
        if not attr_set:
            return frozenset(self.objects)
        idx = [self.attributes.index(m) for m in attr_set if m in self.attributes]
        if not idx:
            return frozenset()
        mask = np.all(self.relation[:, idx], axis=1)
        return frozenset(g for g, v in zip(self.objects, mask) if v)

    # ── Derived operations ──────────────────────────────────────────────────

    def closure(self, attr_set: FrozenSet[str]) -> FrozenSet[str]:
        """
        Attribute closure: B'' = (B')' — the intent of the concept
        generated by attr_set.  Idempotent: (B'')'' = B''.
        Used by NextClosure for canonical implication base.
        """
        return self.object_prime(self.attribute_prime(attr_set))

    def is_closed(self, attr_set: FrozenSet[str]) -> bool:
        """B is closed iff B'' = B  (B is an intent of some formal concept)."""
        return self.closure(attr_set) == attr_set

    def concept_from_intent(self, intent: FrozenSet[str]) -> Tuple[FrozenSet, FrozenSet]:
        """Return the formal concept (A,B) whose intent equals the closure of intent."""
        B = self.closure(intent)
        A = self.attribute_prime(B)
        return A, B

    def concept_from_extent(self, extent: FrozenSet[str]) -> Tuple[FrozenSet, FrozenSet]:
        """Return the formal concept (A,B) generated by extent."""
        A = self.object_prime(extent)           # A'  (= intent B)
        B = self.attribute_prime(A)             # B'  (= closed extent A'')
        return B, A


@dataclass
class FuzzyFormalContext:
    """
    Fuzzy formal context  K_f = (G, M, I_f)
    I_f : G × M → [0,1]   (Singh et al. 2016 Def. 4; Poelmans et al. 2013 §5.4.1)

    Used for handling vague or partially matching problem specifications.
    Membership degrees computed from term-frequency in record corpus.
    """
    objects:    List[str]
    attributes: List[str]
    relation_f: np.ndarray    # float matrix [|G| × |M|], values ∈ [0,1]
    object_data: Dict

    @classmethod
    def from_crisp(cls, ctx: FormalContext) -> "FuzzyFormalContext":
        """Convert crisp FormalContext → FuzzyFormalContext (0→0.0, 1→1.0)."""
        return cls(
            objects=ctx.objects,
            attributes=ctx.attributes,
            relation_f=ctx.relation.astype(float),
            object_data=ctx.object_data,
        )

    def fuzzy_object_prime(
        self, obj_set: FrozenSet[str], threshold: float = 0.5
    ) -> Dict[str, float]:
        """
        Fuzzy A' using Łukasiewicz t-norm (min):
            µ_{A'}(m) = min_{g ∈ A} I_f(g,m)
        Returns {attribute: membership_degree} for degrees ≥ threshold.
        """
        if not obj_set:
            return {a: 1.0 for a in self.attributes}
        idx = [self.objects.index(g) for g in obj_set if g in self.objects]
        if not idx:
            return {}
        memberships = np.min(self.relation_f[idx, :], axis=0)
        return {a: float(v) for a, v in zip(self.attributes, memberships) if v >= threshold}

    def to_crisp(self, threshold: float = 0.5) -> FormalContext:
        """Defuzzify to crisp FormalContext at threshold."""
        return FormalContext(
            objects=self.objects,
            attributes=self.attributes,
            relation=(self.relation_f >= threshold),
            object_data=self.object_data,
        )


@dataclass
class FormalConcept:
    """
    Formal concept C = (A, B)  [Ganter & Wille 1999, Def. 2]

    extent  A ⊆ G : maximal set of objects sharing all attributes in B
    intent  B ⊆ M : maximal set of attributes shared by all objects in A
    label   : human-readable identifier for display
    level   : depth in Hasse diagram (0 = TOP)
    """
    extent:  FrozenSet[str]
    intent:  FrozenSet[str]
    label:   str = ""
    level:   int = 0


@dataclass
class Implication:
    """
    Attribute implication  U → V  over M.
    Holds in K if every object having all attrs in U also has all in V.
    Part of the canonical (Duquenne-Guigues) implication base.
    """
    premise:    FrozenSet[str]    # U ⊆ M
    conclusion: FrozenSet[str]    # V ⊆ M, usually V \ U

    def __repr__(self) -> str:
        P = ", ".join(sorted(self.premise))
        C = ", ".join(sorted(self.conclusion))
        return f"{{{P}}} → {{{C}}}"


@dataclass
class ConceptLattice:
    """
    Concept lattice L(K)  [Ganter & Wille 1999, Theorem 2]

    concepts           : all formal concepts enumerated via NextClosure
    implications       : canonical implication base (Duquenne-Guigues base)
    hasse_edges        : list of (child_idx, parent_idx) for Hasse diagram
    context            : the underlying formal context
    """
    concepts:      List[FormalConcept] = field(default_factory=list)
    implications:  List[Implication]   = field(default_factory=list)
    hasse_edges:   List[Tuple[int,int]] = field(default_factory=list)
    context:       Optional[FormalContext] = None

    def add_concept(self, concept: FormalConcept) -> None:
        """Add concept if not already present (dedup by intent)."""
        for c in self.concepts:
            if c.intent == concept.intent:
                return
        self.concepts.append(concept)

    def find_by_intent(self, intent: FrozenSet[str]) -> Optional[FormalConcept]:
        for c in self.concepts:
            if c.intent == intent:
                return c
        return None

    def summary(self) -> str:
        return (f"ConceptLattice: {len(self.concepts)} concepts, "
                f"{len(self.implications)} implications, "
                f"{len(self.hasse_edges)} Hasse edges")


