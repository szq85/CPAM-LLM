# 6.  Similarity and Retrieval
# ═══════════════════════════════════════════════════════════════════════════════

def weighted_similarity(
    query_attrs: FrozenSet[str],
    concept_intent: FrozenSet[str],
    weights: Optional[Dict[str, float]] = None,
) -> float:
    """
    Weighted Jaccard similarity (Eq. 15):
        score(Q, B) = Σ_{m∈Q∩B} w(m) / Σ_{m∈Q∪B} w(m)
    """
    union = query_attrs | concept_intent
    inter = query_attrs & concept_intent
    if not union:
        return 0.0
    if weights:
        num = sum(weights.get(m, 1.0) for m in inter)
        den = sum(weights.get(m, 1.0) for m in union)
    else:
        num, den = len(inter), len(union)
    return num / den if den > 0 else 0.0


def fuzzy_similarity(
    query_memberships: Dict[str, float],
    concept_memberships: Dict[str, float],
    all_attributes: List[str],
    weights: Optional[Dict[str, float]] = None,
) -> float:
    """
    Fuzzy Jaccard similarity (Eq. 16):
        score_f(Q, B) = Σ_m w·min(µ_Q, µ_B) / Σ_m w·max(µ_Q, µ_B)
    """
    numerator = denominator = 0.0
    for m in all_attributes:
        w    = weights.get(m, 1.0) if weights else 1.0
        mu_q = query_memberships.get(m, 0.0)
        mu_b = concept_memberships.get(m, 0.0)
        numerator   += w * min(mu_q, mu_b)
        denominator += w * max(mu_q, mu_b)
    return numerator / denominator if denominator > 0 else 0.0


