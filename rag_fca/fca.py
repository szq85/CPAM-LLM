# 7.  Rough-set implicit constraint discovery
#     (Eq. 19-22; Yao 2004; Poelmans et al. 2013 §5.4.2)
# ═══════════════════════════════════════════════════════════════════════════════

def discover_implicit_constraints(
    query_attrs: FrozenSet[str],
    lattice: ConceptLattice,
    context: FormalContext,
) -> Tuple[FrozenSet, FrozenSet]:
    """
    Rough-set lower/upper approximation for implicit constraint discovery.
    (Eq. 19-21; Yao 2004; Ganter & Wille 1999 §2.3)

    G_relevant = { g ∈ G | ∃(A,B) ∈ L(K): query_attrs ⊆ B ∧ g ∈ A }
              = lower approximation of query_attrs in L(K)

    certain_constraints  = { m ∈ M\\Q' | ∀g ∈ G_relevant, (g,m) ∈ I }
                         (lower approximation: must appear in all relevant records)
    possible_constraints = { m ∈ M\\Q' | ∃g ∈ G_relevant, (g,m) ∈ I }
                         (upper approximation: may appear in some relevant records)

    Q_augmented = Q' ∪ certain_constraints   (Eq. 22)
    """
    # G_relevant: union of extents of all concepts whose intent contains query_attrs
    g_relevant: FrozenSet[str] = frozenset()
    for concept in lattice.concepts:
        if query_attrs <= concept.intent:
            g_relevant = g_relevant | concept.extent

    if not g_relevant:
        return frozenset(), frozenset()

    obj_indices = [context.objects.index(g) for g in g_relevant if g in context.objects]
    if not obj_indices:
        return frozenset(), frozenset()

    certain  = set()
    possible = set()
    remaining = frozenset(context.attributes) - query_attrs

    for m in remaining:
        a_idx = context.attributes.index(m)
        col   = context.relation[obj_indices, a_idx]
        if np.all(col):
            certain.add(m)
        elif np.any(col):
            possible.add(m)

    return frozenset(certain), frozenset(possible)


def learn_attribute_weights(
    query_log: List[Tuple[FrozenSet[str], bool]],
    all_attributes: List[str],
    prior_weight: float = 1.0,
    positive_boost: float = 0.2,
    negative_decay: float = 0.05,
) -> Dict[str, float]:
    """
    Learn attribute importance weights from historical query logs.
    (Poelmans et al. 2013 §5: attribute implications and their use in retrieval)

    Positive feedback boosts weights; negative feedback decays them.
    Weights normalized to mean=1.0.
    """
    weights = {a: prior_weight for a in all_attributes}
    for attrs, success in query_log:
        delta = positive_boost if success else -negative_decay
        for a in attrs:
            if a in weights:
                weights[a] = max(0.1, weights[a] + delta)
    total = sum(weights.values())
    if total > 0:
        mean = total / len(weights)
        weights = {a: w / mean for a, w in weights.items()}
    return weights
