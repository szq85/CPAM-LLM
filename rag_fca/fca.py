# 5.  FCABuilder — context construction from KB records
# ═══════════════════════════════════════════════════════════════════════════════

class FCABuilder:
    """
    Builds formal contexts and concept lattices from KB record dicts.

    Attribute set M:
      Following the induced-context approach of Kriegel (AAAI-24) and
      Rudolph (2004), attributes are derived from the record corpus:
        - domain/problem-type keywords from PROBLEM_TYPE_ATTRIBUTES
        - constraint keywords from record constraint field
        - structural CP keywords (variable types, constraint operators)
      This gives a finite M from which the incidence I is determined
      by whether (g,m) ∈ I, i.e. attribute m appears in record g's corpus.
    """

    def __init__(self, attribute_config: Dict[str, List[str]] | None = None):
        # Attribute set M is the catalog of named constraint TYPES + objectives
        # + problem-type anchors (paper: M = constraint types, objective
        # functions, solution properties). `attribute_config` is accepted for
        # backward compatibility but no longer drives incidence.
        try:
            from rag_fca import constraints as _con
        except Exception:
            from . import constraints as _con            # type: ignore
        self._con = _con
        self.attribute_config = attribute_config or {}
        self.all_attributes: List[str] = _con.all_named_attributes()

    # ── Context construction ─────────────────────────────────────────────────

    def build_context(self, records: List[Dict]) -> FormalContext:
        """
        Build the formal context K = (G, M, I) from KB records, faithfully to
        the paper (Methods → RAG-FCA, "Formal knowledge representation"):

          G  = problem instances (record ids)
          M  = named constraint types + objective functions + problem-type tags
          I  = (g, m) ∈ I  ⟺  problem g exhibits constraint/characteristic m

        Incidence for each record is computed by `constraints.attributes_for`,
        which uses the exact `Constraint` label when available and falls back
        to NL signature extraction otherwise. This yields a meaningful concept
        lattice whose concepts group problems by shared constraint subsets and
        whose implication base captures real constraint dependencies — unlike
        the previous substring-keyword scheme, which produced a degenerate
        lattice (e.g. the attribute "module" matched every record via the
        phrase "docplex.cp module").
        """
        objects    = [str(r["id"]) for r in records]
        attributes = self.all_attributes
        relation   = np.zeros((len(objects), len(attributes)), dtype=bool)
        attr_idx   = {a: i for i, a in enumerate(attributes)}

        for obj_i, rec in enumerate(records):
            for m in self._con.attributes_for(rec):
                j = attr_idx.get(m)
                if j is not None:
                    relation[obj_i, j] = True

        return FormalContext(
            objects=objects,
            attributes=attributes,
            relation=relation,
            object_data={str(r["id"]): r for r in records},
        )

    def build_fuzzy_context(
        self, records: List[Dict], decay: float = 0.7
    ) -> FuzzyFormalContext:
        """
        Build fuzzy formal context K_f = (G, M, I_f).
        (Singh et al. 2016 Def. 4; Poelmans et al. 2013 §5.4.1)

        I_f(g,m) ∈ [0,1] computed via logarithmic term frequency:
            µ(g,m) = min(1, decay · log(1 + count(m,corpus_g)) / log(1+10))
        Full structural match (from attribute_config) → I_f(g,m) = 1.0.
        """
        ctx = self.build_context(records)
        relation_f = ctx.relation.astype(float)
        attr_idx   = {a: i for i, a in enumerate(ctx.attributes)}

        for obj_i, rec in enumerate(records):
            corpus = " ".join([
                rec.get("nl_text", ""),
                rec.get("constraint_desc", ""),
                rec.get("cp_code", ""),
            ]).lower()
            for attr in ctx.attributes:
                if attr not in attr_idx:
                    continue
                col = attr_idx[attr]
                if relation_f[obj_i, col] == 1.0:
                    continue    # already fully present from structural match
                variants = [attr.lower(), attr.replace("_", " ").lower(),
                            attr.replace("_", "").lower()]
                count = sum(corpus.count(v) for v in variants)
                if count > 0:
                    mu = min(1.0, decay * math.log1p(count) / math.log1p(10))
                    relation_f[obj_i, col] = max(relation_f[obj_i, col], mu)

        return FuzzyFormalContext(
            objects=ctx.objects,
            attributes=ctx.attributes,
            relation_f=relation_f,
            object_data=ctx.object_data,
        )

    def build_lattice(
        self,
        context: FormalContext,
        max_concepts: int = 2000,
        compute_implications: bool = True,
        build_hasse: bool = True,
    ) -> ConceptLattice:
        """
        Build the full concept lattice L(K) via NextClosure.
        (Ganter 1984; Ganter & Wille 1999 §2.4; Poelmans et al. 2013 §2.1)

        Steps:
          1. Enumerate ALL formal concepts using NextClosure (lectic order)
          2. Assign human-readable labels and levels
          3. Optionally compute canonical implication base (Duquenne-Guigues)
          4. Optionally build Hasse diagram (cover relations)

        The TOP concept has extent=G (all objects), BOTTOM has extent=∅.
        Each concept (A,B) satisfies A'=B and B'=A exactly.
        """
        # ── Step 1: enumerate all formal concepts ────────────────────────────
        print(f"  [FCA] Enumerating formal concepts (NextClosure, max={max_concepts})...")
        concepts = enumerate_all_concepts(context, max_concepts=max_concepts)
        print(f"  [FCA] Found {len(concepts)} formal concepts |L(K)|={len(concepts)}")

        # ── Step 2: label concepts ───────────────────────────────────────────
        all_objects  = frozenset(context.objects)
        empty_extent = frozenset()

        for c in concepts:
            if c.extent == all_objects:
                c.label = "⊤ (TOP)"
                c.level = 0
            elif c.extent == empty_extent:
                c.label = "⊥ (BOTTOM)"
                c.level = 99
            else:
                # Label by dominant problem type in extent + first intent attrs
                type_counts: Dict[str, int] = {}
                for g in c.extent:
                    pt = context.object_data.get(g, {}).get("problem_type", "")
                    type_counts[pt] = type_counts.get(pt, 0) + 1
                dominant = max(type_counts, key=type_counts.get) if type_counts else ""
                label_attrs = sorted(c.intent)[:3]
                c.label = f"{dominant[:12]}|{','.join(label_attrs)}"
                # Level: inversely proportional to extent size
                c.level = 1 if len(c.extent) > len(context.objects) // 2 else (
                           2 if len(c.extent) > 1 else 3)

        # ── Step 3: canonical implication base ───────────────────────────────
        implications: List[Implication] = []
        if compute_implications and len(context.attributes) <= 64:
            print("  [FCA] Computing canonical implication base (Duquenne-Guigues)...")
            implications = compute_implication_base(context, max_implications=1000)
            print(f"  [FCA] Implication base: {len(implications)} implications")

        # ── Step 4: Hasse diagram ────────────────────────────────────────────
        hasse_edges: List[Tuple[int,int]] = []
        if build_hasse and len(concepts) <= 500:
            print("  [FCA] Building Hasse diagram (cover relations)...")
            hasse_edges = build_hasse_diagram(concepts)
            print(f"  [FCA] Hasse edges: {len(hasse_edges)}")

        lattice = ConceptLattice(
            concepts=concepts,
            implications=implications,
            hasse_edges=hasse_edges,
            context=context,
        )
        return lattice


